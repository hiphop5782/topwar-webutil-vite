import assert from 'node:assert/strict';
import { executeDataQuery, querySnapshot, resolveQueryDates, summarizeServerHistory, validateDataQuery } from '../src/ai/dataQuery.js';
import { parseChatResponse } from '../src/ai/chatClient.js';

const player = (uid, nickname, server, power, allianceId, allianceTag) => ({ uid, nickname, server, power, allianceId, allianceTag, allianceName: allianceTag, observedAt: '2026-11-27T00:00:00Z' });
const a = player('1', 'Alpha', 3223, 100, '10', 'AAA');
const document = { sourceUpdatedAt: '2026-11-27T00:00:00Z', players: [a, a, player('2', 'Beta', 3223, null, '10', 'AAA'), player('3', 'Alpha', 3224, 300, '20', 'BBB'), player('4', 'Delta', 3224, 500, '21', 'AAA')] };
const target = (server = 0, name = '', uid = '') => ({ server, name, uid });
const plan = (kind, targets) => ({ kind, targets, startDate: '', endDate: '' });
const servers = plan('server_compare', [target(3223), target(3224)]);
const serverResult = querySnapshot(document, servers);
assert.deepEqual(serverResult.rows[0], ['s3223', 3223, '2', '1', '100', '100', '100']);
assert.deepEqual(serverResult.rows[1], ['s3224', 3224, '2', '2', '800', '400', '500']);
assert.equal(querySnapshot(document, plan('server_summary', [target(3223)])).rows.length, 1);
assert.equal(querySnapshot(document, plan('player_summary', [target(0, 'Alpha')])).rows.length, 2);
assert.equal(querySnapshot(document, plan('player_summary', [target(3223, 'Alpha')])).context.targets[0].uid, '1');
assert.equal(querySnapshot(document, plan('player_compare', [target(0, '', '1'), target(0, '', '3')])).rows.length, 2);
assert.equal(querySnapshot(document, plan('guild_compare', [target(3223, 'AAA'), target(3224, 'BBB')])).rows[0][2], '2');
assert.match(querySnapshot(document, plan('guild_compare', [target(0, 'AAA'), target(3224, 'BBB')])).text, /특정하지/);
assert.match(querySnapshot(document, plan('server_summary', [target(9999)])).text, /찾지 못/);
assert.throws(() => validateDataQuery({ ...servers, startDate: '2026-11-01' }), /최신 스냅샷/);
assert.throws(() => validateDataQuery(plan('server_compare', [target(3223)])), /두 개 이상/);
assert.throws(() => validateDataQuery({ ...plan('server_history', [target(3223)]), startDate: '2026-02-30' }), /YYYY/);
const historyPlan = { ...plan('server_history', [target(3223)]), startDate: '2026-11-01', endDate: '2026-11-27' };
assert.equal(resolveQueryDates(historyPlan, '최근 한달 이력', new Date('2026-11-27')).startDate, '2026-10-29');
assert.equal(resolveQueryDates(historyPlan, '지난달 이력', new Date('2026-01-27')).startDate, '2025-12-01');
assert.equal(resolveQueryDates(historyPlan, '최근 7일 이력', new Date('2026-11-27')).startDate, '2026-11-21');
const movement = { uid: '1', nickname: 'Alpha', fromServer: 3224, toServer: 3223, detectedAt: '2026-11-26T12:00:00Z' };
const files = [{ date: '2026-11-26', path: 'overall/movement/2026-11-26.json' }, { date: '2026-11-27', path: 'overall/movement/2026-11-27.json' }];
const result = summarizeServerHistory(historyPlan, files, [{ status: 'fulfilled', value: { rows: [movement, movement, { ...movement, detectedAt: '2026-10-01T00:00:00Z' }] } }, { status: 'rejected' }]);
assert.equal(result.rows.length, 1);
assert.match(result.text, /유입 1건, 유출 0건/);
assert.match(result.text, /불완전/);
assert.equal(result.sources.length, 1);
assert.match(summarizeServerHistory(historyPlan, [], []).text, /확인할 수 없습니다/);
let active = 0;
let peak = 0;
await executeDataQuery(historyPlan, { listOverallHistoryFiles: async () => Array.from({ length: 9 }, () => files[0]), loadDataFile: async () => { active++; peak = Math.max(peak, active); await new Promise(resolve => setTimeout(resolve, 5)); active--; return { rows: [] }; } });
assert.equal(peak, 4);
const parsed = parseChatResponse({ message: { content: JSON.stringify({ type: 'data', reply: 'made-up response ignored', plan: servers }) } });
assert.equal(parsed.reply, undefined);
assert.deepEqual(parsed.plan, servers);
console.log('PASS all 6 query kinds, duplicate UID, missing power, ambiguous names/guilds, dates, partial failures, deduplicated history, concurrency and validated model plans');
